    /**
     * 随机返回一个主题设备名，尽量与 [exclude] 不同，避免连续两次抽到同一个。
     */
    fun random(exclude: String? = null): String {
        if (THEMED.size <= 1) return Settings.normalizeDeviceName(THEMED.first())
        val normalizedExclude = Settings.normalizeDeviceName(exclude)
        var pick = Settings.normalizeDeviceName(THEMED.random())
        var guard = 0
        while (pick == normalizedExclude && guard < 8) {
            pick = Settings.normalizeDeviceName(THEMED.random())
            guard++
        }
        return Settings.normalizeDeviceName(pick)
    }
